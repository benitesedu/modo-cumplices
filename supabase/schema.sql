-- Execute este script no SQL Editor do projeto Supabase.
create table if not exists public.dias (
  dia date primary key,
  marcacoes text[] not null default '{}',
  envolvidos_na_briga text,
  observacao text not null default '',
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  constraint dias_marcacoes_check check (cardinality(marcacoes) > 0),
  constraint dias_envolvido_check check (envolvidos_na_briga is null or envolvidos_na_briga in ('Os dois', 'Eduardo', 'Jéssica'))
);

create table if not exists public.votos (
  dia date not null references public.dias(dia) on delete cascade,
  participante text not null,
  estrelas smallint not null,
  comentario text not null default '',
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  primary key (dia, participante),
  constraint votos_participante_check check (participante in ('eduardo', 'jessica')),
  constraint votos_estrelas_check check (estrelas between 1 and 5)
);

create or replace function public.atualizar_atualizado_em()
returns trigger
language plpgsql
as $$
begin
  new.atualizado_em = now();
  return new;
end;
$$;

drop trigger if exists dias_atualizado_em on public.dias;
create trigger dias_atualizado_em
before update on public.dias
for each row execute function public.atualizar_atualizado_em();

drop trigger if exists votos_atualizado_em on public.votos;
create trigger votos_atualizado_em
before update on public.votos
for each row execute function public.atualizar_atualizado_em();

-- A API da Vercel usa a service role key no servidor. O acesso público direto fica bloqueado.
alter table public.dias enable row level security;
alter table public.votos enable row level security;

grant usage on schema public to service_role;
grant select, insert, update, delete on public.dias to service_role;
grant select, insert, update, delete on public.votos to service_role;

create table if not exists public.eventos_especiais (
  id bigint generated by default as identity primary key,
  tipo text not null,
  participante text not null,
  data_inicio date not null,
  data_fim date not null,
  descricao text not null default '',
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  constraint eventos_tipo_check check (tipo in ('Viagem', 'Passeio', 'Acontecimento')),
  constraint eventos_participante_check check (participante in ('Eduardo', 'Jéssica', 'Ambos')),
  constraint eventos_periodo_check check (data_fim >= data_inicio)
);

create table if not exists public.eventos_itens (
  id bigint generated by default as identity primary key,
  evento_id bigint not null references public.eventos_especiais(id) on delete cascade,
  data date not null,
  observacao text not null,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

create or replace function public.validar_data_item_evento()
returns trigger
language plpgsql
as $$
declare
  inicio date;
  fim date;
begin
  select data_inicio, data_fim into inicio, fim
  from public.eventos_especiais where id = new.evento_id;
  if inicio is null or new.data < inicio or new.data > fim then
    raise exception 'A data do item precisa estar dentro do período do evento';
  end if;
  return new;
end;
$$;

drop trigger if exists validar_data_item_evento on public.eventos_itens;
create trigger validar_data_item_evento
before insert or update on public.eventos_itens
for each row execute function public.validar_data_item_evento();

drop trigger if exists eventos_atualizado_em on public.eventos_especiais;
create trigger eventos_atualizado_em
before update on public.eventos_especiais
for each row execute function public.atualizar_atualizado_em();

drop trigger if exists eventos_itens_atualizado_em on public.eventos_itens;
create trigger eventos_itens_atualizado_em
before update on public.eventos_itens
for each row execute function public.atualizar_atualizado_em();

alter table public.eventos_especiais enable row level security;
alter table public.eventos_itens enable row level security;
grant usage, select on sequence public.eventos_especiais_id_seq to service_role;
grant usage, select on sequence public.eventos_itens_id_seq to service_role;
grant select, insert, update, delete on public.eventos_especiais to service_role;
grant select, insert, update, delete on public.eventos_itens to service_role;
